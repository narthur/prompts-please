// The summary uses local time; pin it so the expected times hold anywhere.
process.env.TZ = 'UTC'

import { appendFileSync, mkdirSync, mkdtempSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { beforeEach, expect, test } from 'vitest'
import { submit, stamp, readLedger, dailySummary, listHall, decisionFor } from '../src/bureau.ts'

const writeCall = JSON.parse(readFileSync(new URL('./pretooluse-write.json', import.meta.url), 'utf8'))
const call = (id: string) => ({ ...writeCall, tool_use_id: id })

let dir: string
beforeEach(() => { dir = mkdtempSync(join(tmpdir(), 'ledger-')) })

test('each stamp is recorded in the ledger with the visitor, verdict and time', () => {
  submit(dir, call('toolu_a'))
  stamp(dir, 'toolu_a', { verdict: 'refuse', reason: 'Not today.' }, new Date('2026-11-01T10:00:00Z'))

  expect(readLedger(dir)).toEqual([{
    type: 'stamp',
    at: '2026-11-01T10:00:00.000Z',
    toolUseId: 'toolu_a',
    sessionId: writeCall.session_id,
    cwd: writeCall.cwd,
    toolName: 'Write',
    toolInput: writeCall.tool_input,
    decision: { verdict: 'refuse', reason: 'Not today.' },
  }])
})

test('the ledger only grows: later stamps are appended after earlier ones', () => {
  submit(dir, call('toolu_a'))
  submit(dir, call('toolu_b'))
  stamp(dir, 'toolu_a', { verdict: 'admit' })
  const before = readFileSync(join(dir, 'ledger.jsonl'), 'utf8')

  stamp(dir, 'toolu_b', { verdict: 'admit' })

  const after = readFileSync(join(dir, 'ledger.jsonl'), 'utf8')
  expect(after.startsWith(before)).toBe(true)
  expect(readLedger(dir).map((e) => e.toolUseId)).toEqual(['toolu_a', 'toolu_b'])
})

test('a stamp that fails leaves no ledger entry', () => {
  expect(() => stamp(dir, 'toolu_missing', { verdict: 'admit' })).toThrow()
  expect(readLedger(dir)).toEqual([])
})

test('the daily summary lists that day’s stamps, one line each', () => {
  submit(dir, call('toolu_a'))
  submit(dir, call('toolu_b'))
  submit(dir, call('toolu_c'))
  stamp(dir, 'toolu_a', { verdict: 'admit' }, new Date('2026-10-31T23:00:00Z'))
  stamp(dir, 'toolu_b', { verdict: 'admit' }, new Date('2026-11-01T09:15:00Z'))
  stamp(dir, 'toolu_c', { verdict: 'return', note: 'Use docs/.' }, new Date('2026-11-01T09:20:00Z'))

  const md = dailySummary(readLedger(dir), '2026-11-01')

  expect(md).toBe([
    '# Bureau ledger 2026-11-01',
    '',
    '_Generated by Prompts Please after each stamp; edits here are overwritten._',
    '',
    '2 stamps: 1 admitted, 0 refused, 1 returned.',
    '',
    '- 09:15 **Admit** Write in `work`',
    '- 09:20 **Return** Write in `work`: Use docs/.',
    '',
  ].join('\n'))
})

test('lines in the ledger that are not stamps are skipped', () => {
  submit(dir, call('toolu_a'))
  stamp(dir, 'toolu_a', { verdict: 'admit' })
  appendFileSync(join(dir, 'ledger.jsonl'), '{}\nnull\n{"type":"stamp","decision":{"verdict":"deny"}}\nnot json\n')

  expect(readLedger(dir).map((e) => e.toolUseId)).toEqual(['toolu_a'])
})

test('agent-written text cannot inject Markdown or wiki links into the summary', () => {
  submit(dir, { ...call('toolu_a'), cwd: '/x/we`ird' })
  stamp(dir, 'toolu_a', { verdict: 'refuse', reason: 'see [[secrets]] and `rm -rf` **now**' }, new Date('2026-11-01T09:00:00Z'))

  const line = dailySummary(readLedger(dir), '2026-11-01').split('\n').find((l) => l.startsWith('- '))

  expect(line).toBe('- 09:00 **Refuse** Write in `we\'ird`: see \\[\\[secrets\\]\\] and \\`rm -rf\\` \\*\\*now\\*\\*')
})

test('a torn last line (crash mid-append) does not swallow the next stamp', () => {
  appendFileSync(join(dir, 'ledger.jsonl'), '{"type":"stamp","at":"2026-')
  submit(dir, call('toolu_a'))
  stamp(dir, 'toolu_a', { verdict: 'admit' })

  expect(readLedger(dir).map((e) => e.toolUseId)).toEqual(['toolu_a'])
})

test('if the ledger cannot be written, the visitor stays in the hall undecided', () => {
  mkdirSync(join(dir, 'ledger.jsonl')) // appending to a directory fails
  submit(dir, call('toolu_a'))

  expect(() => stamp(dir, 'toolu_a', { verdict: 'admit' })).toThrow()
  expect(listHall(dir).map((v) => v.toolUseId)).toEqual(['toolu_a'])
  expect(decisionFor(dir, 'toolu_a')).toBeNull()
})
